import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = await mkdtemp(join(tmpdir(), 'soluna-sun-web-'));
process.env.SOLUNA_HOME = join(root, 'config');
const { startWebServer } = await import('../src/web/server.js');
const { loadConfig } = await import('../src/core/session-store.js');

test('web Sun catalog, refresh, key persistence and provider/model selection work together', async (t) => {
  let requests = 0;
  const upstreamModels = Array.from({ length: 65 }, (_, i) => ({ id: `sun-model-${i}`, name: `Sun model ${i}`, available: true, capabilities: { tools: i % 2 === 0 } }));
  const options = { cwd: root, host: '127.0.0.1', port: 0, noMcp: true, token: 'sun-web-test', modelFetch: async (url, request) => {
    assert.equal(url, 'https://sun.soymaycol.icu/api/models');
    assert.equal(request.headers.Authorization, undefined);
    requests++;
    return Response.json({ apiVersion: 'v1', healthy: true, models: upstreamModels });
  } };
  let instance = await startWebServer(options);
  t.after(async () => { await instance.close(); await rm(root, { recursive: true, force: true }); });
  let base = `http://127.0.0.1:${instance.server.address().port}`;
  const headers = { Authorization: 'Bearer sun-web-test', 'Content-Type': 'application/json' };
  const get = (path) => fetch(base + path, { headers }).then((r) => r.json());
  const post = (path, body) => fetch(base + path, { method: 'POST', headers, body: JSON.stringify(body) });
  assert.equal((await fetch(base + '/api/models?provider=sun')).status, 401);
  const catalog = await get('/api/models?provider=sun');
  assert.equal(catalog.models.length, 65);
  assert.equal(catalog.source, 'sun');
  await get('/api/models?provider=sun');
  assert.equal(requests, 1);
  await get('/api/models?provider=sun&refresh=1');
  assert.equal(requests, 2);
  assert.equal((await post('/api/set-provider', { provider: 'sun' })).status, 400);
  const keys = ['sun_live_test_first_key_1234', 'sun_live_test_second_key_5678'];
  const added = await post('/api/keys', { provider: 'sun', keys });
  assert.equal(added.status, 200);
  const saved = await added.json();
  assert.equal(saved.keys.length, 2);
  assert.ok(keys.every((key) => !JSON.stringify(saved).includes(key)));
  assert.equal((await post('/api/set-provider', { provider: 'sun' })).status, 200);
  assert.equal((await post('/api/set-model', { model: 'sun-model-64' })).status, 200);
  const config = await get('/api/config');
  assert.equal(config.providers.find((p) => p.id === 'sun').ready, true);
  assert.equal(config.providers.find((p) => p.id === 'sun').dynamic, true);
  assert.equal(config.current.model, 'sun-model-64');
  assert.equal((await loadConfig()).apiKeys.sun, keys[0]);
  assert.deepEqual((await loadConfig()).apiKeyPools.sun, [keys[1]]);
  await instance.close();
  instance = await startWebServer(options); base = `http://127.0.0.1:${instance.server.address().port}`;
  assert.equal((await get('/api/config')).current.provider, 'sun');
  assert.equal((await get('/api/keys?provider=sun')).keys.length, 2);
});
